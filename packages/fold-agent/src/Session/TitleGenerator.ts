import type { AssistantMessageLogEntry, LogEntry, FoldModel, UserMessageLogEntry } from '@humanlayer/fold-core'
import { encodedContentText } from '@humanlayer/fold-core'
import { Context, Predicate, Effect, Layer, Schema, type Scope } from 'effect'

const TitleResult = Schema.Struct({ title: Schema.String })
const MAX_TRANSCRIPT_CHARS = 12_000

type MessageEntry = UserMessageLogEntry | AssistantMessageLogEntry

const isMessageEntry = (entry: LogEntry): entry is MessageEntry =>
	Predicate.isTagged(entry, 'user-message') || Predicate.isTagged(entry, 'assistant-message')

const messageText = (entry: LogEntry): string =>
	isMessageEntry(entry) ? encodedContentText(entry.message.content) : ''

/** Normalize model output to a single, safe title of at most six words. */
export const normalizeSessionTitle = (title: string): string =>
	title
		.replace(/[\r\n]+/g, ' ')
		.replace(/^[\s"'`]+|[\s"'`]+$/g, '')
		.replace(/\s+/g, ' ')
		.split(' ')
		.filter(Boolean)
		.slice(0, 6)
		.join(' ')

export const fallbackSessionTitle = (entries: ReadonlyArray<LogEntry>, rootAgentId: string): string => {
	const first = entries.find((entry) => Predicate.isTagged(entry, 'user-message') && entry.agentId === rootAgentId)
	return normalizeSessionTitle(first === undefined ? '' : messageText(first)) || 'Untitled session'
}

/** Root user/assistant text only, bounded from the oldest root turn forward. */
export const titleTranscript = (entries: ReadonlyArray<LogEntry>, rootAgentId: string): string =>
	entries
		.filter(
			(entry) =>
				entry.agentId === rootAgentId &&
				(Predicate.isTagged(entry, 'user-message') || Predicate.isTagged(entry, 'assistant-message')),
		)
		.map((entry) => `${Predicate.isTagged(entry, 'user-message') ? 'User' : 'Assistant'}: ${messageText(entry)}`)
		.join('\n')
		.slice(0, MAX_TRANSCRIPT_CHARS)

/** Generates session titles over one LanguageModel built once per session. */
export type SessionTitleGeneratorService = {
	/** One unlogged structured generation call. Callers persist only the resulting session_title event. */
	readonly generate: (entries: ReadonlyArray<LogEntry>, rootAgentId: string) => Effect.Effect<string>
}

const makeSessionTitleGenerator = <R>(
	model: FoldModel<R>,
): Effect.Effect<SessionTitleGeneratorService, never, Scope.Scope | R> =>
	Effect.gen(function* () {
		const languageModel = yield* model.make

		return {
			generate: (entries, rootAgentId) => {
				const fallback = fallbackSessionTitle(entries, rootAgentId)
				const transcript = titleTranscript(entries, rootAgentId)
				if (transcript.length === 0) return Effect.succeed(fallback)

				return languageModel
					.generateObject({
						schema: TitleResult,
						prompt:
							'Create a concise title of at most six words for this coding session. Return only the structured title.\n\n' +
							transcript,
					})
					.pipe(
						Effect.map((response) => normalizeSessionTitle(response.value.title) || fallback),
						Effect.catchCause(() => Effect.succeed(fallback)),
					)
			},
		}
	})

/** One session's title generator. The host provides it per session; title generation asks for it. */
export class SessionTitleGenerator extends Context.Service<SessionTitleGenerator, SessionTitleGeneratorService>()(
	'fold-agent/Session/SessionTitleGenerator',
) {
	/** Titles generated by `model`, whose LanguageModel is built once in the layer's scope. */
	static readonly layer = <R>(
		model: FoldModel<R>,
	): Layer.Layer<SessionTitleGenerator, never, Exclude<R, Scope.Scope>> =>
		Layer.effect(this, makeSessionTitleGenerator(model))
}
